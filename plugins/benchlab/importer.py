GAIA_DATASET = "gaia-benchmark/GAIA"
_GAIA_ROWS_URL = ("https://datasets-server.huggingface.co/rows"
                  "?dataset=gaia-benchmark%2FGAIA&config=2023_level1"
                  "&split=validation&offset={offset}&length={length}")
_GAIA_FILE_URL = ("https://huggingface.co/datasets/gaia-benchmark/GAIA"
                  "/resolve/main/{path}")
_GAIA_MAX_ATTACHMENT = 256 * 1024

# The official GAIA prompt suffix (Mialon et al. 2023, arXiv:2311.12983,
# appendix) — the harness's answer_exact_any scorer keys on the FINAL ANSWER
# marker, exactly like the real GAIA scorer.
GAIA_SUFFIX = (
    "You are a general AI assistant. I will ask you a question. Report your "
    "thoughts, and finish your answer with the following template: "
    "FINAL ANSWER: [YOUR FINAL ANSWER]. YOUR FINAL ANSWER should be a number "
    "OR as few words as possible OR a comma separated list of numbers and/or "
    "strings. If you are asked for a number, don't use comma to write your "
    "number neither use units such as $ or percent sign unless specified "
    "otherwise. If you are asked for a string, don't use articles, neither "
    "abbreviations (e.g. for cities), and write the digits in plain text "
    "unless specified otherwise. If you are asked for a comma separated "
    "list, apply the above rules depending of whether the element to be put "
    "in the list is a number or a string.")

GAIA_JUDGE_RUBRIC = "Exact-match case: pass iff deterministic checks passed."

GAIA_TOKEN_HELP = ("GAIA is a gated HF dataset: set HF_TOKEN in the service "
                   "environment (e.g. ~/.config/jaynet.env) to a token with "
                   "read access to gaia-benchmark/GAIA, then restart. The "
                   "token is read from the process env and never logged.")


def _http_get(url: str, token: str | None, timeout: int = 60) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "jaynet-benchlab"})
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.read()
    except urllib.error.HTTPError as e:
        if e.code in (401, 403):
            raise RuntimeError("HF rejected the token (gated dataset). "
                               + GAIA_TOKEN_HELP) from e
        # The datasets-server answers "gated + no access" with a 404 whose
        # body SAYS so — surface HF's own explanation instead of a bare
        # "not found" that sends operators hunting for a wrong URL.
        try:
            detail = e.read().decode("utf-8", "replace").strip()[:300]
        except OSError:
            detail = ""
        msg = f"HTTP {e.code} from Hugging Face: {url}"
        if detail:
            msg += f" — {detail}"
        if e.code == 404:
            msg += " (a 404 here usually means the token has no access to " \
                   "the gated dataset — " + GAIA_TOKEN_HELP + ")"
        raise RuntimeError(msg) from e
    except urllib.error.URLError as e:
        raise RuntimeError(f"cannot reach Hugging Face: {e.reason}") from e


def fetch_gaia_rows(token: str, limit: int = 50) -> list[dict]:
    """Level-1 validation rows via the HF datasets-server (no `datasets`
    package needed). `limit` caps how many rows are pulled."""
    rows: list[dict] = []
    offset = 0
    while len(rows) < limit:
        length = min(100, limit - len(rows))
        data = json.loads(_http_get(
            _GAIA_ROWS_URL.format(offset=offset, length=length), token))
        batch = data.get("rows") or []
        if not batch:
            break
        rows.extend(b.get("row") or {} for b in batch)
        offset += len(batch)
    return rows[:limit]


def fetch_gaia_attachment(token: str, file_path: str) -> bytes:
    """Download one GAIA attachment file from the dataset repo."""
    quoted = urllib.parse.quote(str(file_path).lstrip("/"))
    return _http_get(_GAIA_FILE_URL.format(path=quoted), token, timeout=120)


def gaia_row_to_case(row: dict, attachment: bytes | None = None,
                     attachment_name: str = "") -> dict:
    """Convert one GAIA metadata row (+ optional downloaded attachment bytes)
    into an answer_exact_any eval case dict."""
    question = str(row.get("Question") or "").strip()
    # HF's schema spells it "Final answer" (space); accept the underscore
    # variant too so older fixtures/fixtures by hand keep working.
    gold = str(row.get("Final answer") or row.get("Final_answer")
               or "").strip()
    task_id = str(row.get("task_id") or "").strip()
    if not question or not gold or not task_id:
        raise SkipTask("row misses Question/Final_answer/task_id")
    turn = question
    project: dict = {}
    if attachment_name:
        if attachment is None:
            raise SkipTask(f"attachment '{attachment_name}' not downloaded")
        if len(attachment) > _GAIA_MAX_ATTACHMENT:
            raise SkipTask(f"attachment '{attachment_name}' too large "
                           f"({len(attachment)} bytes)")
        project = _fixtures_to_project({attachment_name: attachment})
        turn += (f"\n\nThe referenced file '{attachment_name}' is in the "
                 f"current project directory.")
    turn += "\n\n" + GAIA_SUFFIX
    short = question if len(question) <= 70 else question[:67].rstrip() + "..."
    case = {
        "id": sanitize_task_id("gaia", task_id[:8]),
        "name": f"GAIA level-1: {short}",
        "tags": ["bench", "gaia"],
        "driver": "scripted",
        "turns": [{"user": turn}],
        "expect": {"answer_exact_any": [gold]},
        "judge_rubric": GAIA_JUDGE_RUBRIC,
    }
    if project:
        case["project"] = project
    return case


# ---- writing ---------------------------------------------------------------------

def write_cases(cases: list[dict], out_dir: Path) -> dict:
    """Validate, dump and write each case as <id>.yaml into out_dir (the
    custom evals layer — cases show up in Admin → Eval). Each written file is
    parsed back as proof. Only ids we generated (tb-*/gaia-*) are written, so
    re-imports overwrite benchlab's own cases and never touch other files."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    imported: list[str] = []
    failed: list[dict] = []
    for case in cases:
        cid = str(case.get("id") or "?")
        try:
            errors = validate_case_dict(cid, case)
            if errors:
                raise ValueError("; ".join(errors))
            text = yaml.safe_dump(case, sort_keys=False, allow_unicode=True,
                                  width=100)
            parse_case(cid, text, "custom")          # prove the file loads
            (out_dir / f"{cid}.yaml").write_text(text, encoding="utf-8")
            imported.append(cid)
        except (ValueError, OSError, yaml.YAMLError) as e:
            log.warning("benchlab: case %s failed to write: %s", cid, e)
            failed.append({"id": cid, "error": str(e)})
    return {"imported": imported, "failed": failed, "dir": str(out_dir)}
